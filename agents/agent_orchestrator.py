"""
Orion — Agent Orchestrator for Multi-Agent Maintenance Block Coordination.
Coordinates the end-to-end multi-agent negotiation workflow:
1. Department Agents (Engineering, S&T, TRD) evaluate backlogs & bid
2. Arbitrator Agent mediates conflicts and executes Block Merging
3. Early Warning Agent identifies compounding risks
4. Synthesizes a consensus BlockPlan with transparent decision traces
"""
from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone
from typing import Any, Dict, List, Optional

from railopt.models import (
    BlockPlan,
    BlockType,
    BlockWindow,
    Corridor,
    Department,
    EarlyWarning,
    MaintenanceTask,
    PlanHorizon,
    ScheduledBlock,
    Section,
    TaskStatus,
)

from .arbitrator_agent import ArbitratorAgent, ConflictResolution, NegotiationAgreement
from .department_agent import DepartmentAgent, DepartmentProposal
from .early_warning_agent import EarlyWarningAgent

logger = logging.getLogger(__name__)


@dataclass
class AgentConsensusPlan:
    """The unified schedule and negotiation audit trail generated by the multi-agent system."""
    plan: BlockPlan
    department_proposals: List[DepartmentProposal]
    agreements: List[NegotiationAgreement]
    conflict_resolutions: List[ConflictResolution]
    early_warnings: List[EarlyWarning]
    orchestration_summary: Dict[str, Any]


class AgentOrchestrator:
    """
    Coordinates collaborative agent interactions between Department Agents,
    the Traffic Arbitrator, and the Predictive Risk Monitor.
    """

    def __init__(self):
        self.engineering_agent = DepartmentAgent(Department.ENGINEERING)
        self.snt_agent = DepartmentAgent(Department.SNT)
        self.trd_agent = DepartmentAgent(Department.TRD)
        self.arbitrator = ArbitratorAgent()
        self.early_warning_agent = EarlyWarningAgent()

    def run_planning_cycle(
        self,
        tasks: List[MaintenanceTask],
        available_windows: List[BlockWindow],
        sections: Dict[str, Section],
        corridors: List[Corridor],
        horizon: PlanHorizon = PlanHorizon.WEEKLY,
        start_date: Optional[date] = None,
    ) -> AgentConsensusPlan:
        """
        Executes the multi-agent negotiation workflow and returns an agreed schedule.
        """
        plan_start = start_date or date.today()
        days_ahead = 7 if horizon == PlanHorizon.WEEKLY else (30 if horizon == PlanHorizon.MONTHLY else 1)
        plan_end = plan_start + timedelta(days=days_ahead)

        logger.info("AgentOrchestrator: Initiating multi-agent planning cycle (%s to %s)", plan_start, plan_end)

        # Step 1: Department Agents formulate proposals
        eng_proposals = self.engineering_agent.formulate_proposals(tasks, available_windows, sections)
        snt_proposals = self.snt_agent.formulate_proposals(tasks, available_windows, sections)
        trd_proposals = self.trd_agent.formulate_proposals(tasks, available_windows, sections)

        all_proposals = eng_proposals + snt_proposals + trd_proposals
        logger.info(
            "Agent proposals generated: ENG=%d, SNT=%d, TRD=%d (Total=%d)",
            len(eng_proposals), len(snt_proposals), len(trd_proposals), len(all_proposals)
        )

        # Step 2: Arbitrator Agent resolves conflicts and performs Block Merging
        agreements, conflict_resolutions = self.arbitrator.arbitrate(all_proposals)
        logger.info(
            "Arbitration completed: %d agreements synthesized (%d conflicts mediated)",
            len(agreements), len(conflict_resolutions)
        )

        # Step 3: Early Warning Agent scans infrastructure risks
        early_warnings = self.early_warning_agent.scan_corridor_risks(
            tasks=tasks,
            corridors=corridors,
            sections=sections,
            current_date=plan_start,
        )
        logger.info("Early Warning scan: %d proactive risks detected", len(early_warnings))

        # Step 4: Build scheduled blocks from agreements
        scheduled_blocks: List[ScheduledBlock] = []
        scheduled_task_ids: List[str] = []
        total_merge_savings = 0.0

        for ag in agreements:
            sec_name = sections.get(ag.section_id).name if ag.section_id in sections else ag.section_id
            from traffic.section_map import is_pilot_section, get_pilot_section_config
            from traffic.fill import get_all_passages_for_section
            from traffic.delay_model import calculate_block_delays
            from traffic.cascade import propagate_cascade

            if is_pilot_section(ag.section_id):
                sec_cfg = get_pilot_section_config(ag.section_id)
                passages, _ = get_all_passages_for_section(sec_cfg, ag.target_date)
                prim = calculate_block_delays(sec_cfg, ag.target_date, ag.start_time, ag.end_time, passages)
                cas = propagate_cascade(prim, passages)
                t_aff = cas.trains_hit
                cum_delay = cas.cascade_total_delay
            else:
                sec_obj = sections.get(ag.section_id)
                density_factor = 1.0
                if sec_obj and hasattr(sec_obj, "traffic_density_class"):
                    density_factor = {"A_SPECIAL": 2.2, "A": 1.8, "B": 1.2, "C": 0.6, "D": 0.3}.get(
                        str(getattr(sec_obj.traffic_density_class, "value", sec_obj.traffic_density_class)), 1.0
                    )
                t_aff = max(0, int(ag.duration_hours * 1.1 * density_factor))
                cum_delay = round(t_aff * 12.5, 1)

            blk = ScheduledBlock(
                block_id=f"BLK-{uuid.uuid4().hex[:8].upper()}",
                window_id=ag.window_id or f"WIN-{uuid.uuid4().hex[:6].upper()}",
                corridor_id=ag.corridor_id,
                section_id=ag.section_id,
                section_name=sec_name,
                date=ag.target_date,
                start_time=ag.start_time,
                end_time=ag.end_time,
                duration_hours=ag.duration_hours,
                task_ids=ag.task_ids,
                departments=ag.participating_departments,
                block_type=ag.block_type,
                trains_affected=t_aff,
                cumulative_delay_minutes=cum_delay,
                is_merged=ag.is_merged,
                merge_savings_hours=ag.merge_savings_hours,
                justification=ag.rationale,
            )
            scheduled_blocks.append(blk)
            scheduled_task_ids.extend(ag.task_ids)
            total_merge_savings += ag.merge_savings_hours

        # Update task statuses
        scheduled_set = set(scheduled_task_ids)
        deferred_task_ids: List[str] = []
        dept_counts: Dict[str, int] = {}

        for t in tasks:
            if t.task_id in scheduled_set:
                t.status = TaskStatus.SCHEDULED
                dept_counts[t.department.value] = dept_counts.get(t.department.value, 0) + 1
            elif t.status in (TaskStatus.PENDING, TaskStatus.UNVERIFIED, TaskStatus.ESCALATED):
                t.status = TaskStatus.DEFERRED
                t.deferred_count += 1
                deferred_task_ids.append(t.task_id)

        # Step 5: Synthesize standard BlockPlan
        plan = BlockPlan(
            plan_id=f"PLN-AGENT-{uuid.uuid4().hex[:8].upper()}",
            horizon=horizon,
            start_date=plan_start,
            end_date=plan_end,
            created_at=datetime.now(timezone.utc),
            scheduled_blocks=scheduled_blocks,
            total_tasks_scheduled=len(scheduled_task_ids),
            total_tasks_deferred=len(deferred_task_ids),
            total_block_hours=sum(b.duration_hours for b in scheduled_blocks),
            total_merge_savings_hours=round(total_merge_savings, 1),
            total_trains_affected=sum(b.trains_affected for b in scheduled_blocks),
            sla_compliance_pct=round(
                (len(scheduled_task_ids) / max(len(scheduled_task_ids) + len(deferred_task_ids), 1)) * 100.0, 1
            ),
            departments_summary=dept_counts,
            deferred_task_ids=deferred_task_ids,
            solver_status="AGENT_CONSENSUS_OPTIMAL",
            status="DRAFT",
        )

        summary = {
            "proposals_submitted": len(all_proposals),
            "proposals_by_department": {
                "ENGINEERING": len(eng_proposals),
                "SNT": len(snt_proposals),
                "TRD": len(trd_proposals),
            },
            "agreements_reached": len(agreements),
            "merged_blocks_count": sum(1 for a in agreements if a.is_merged),
            "hours_saved_by_merging": round(total_merge_savings, 1),
            "conflicts_resolved": len(conflict_resolutions),
            "early_warnings_flagged": len(early_warnings),
            "consensus_rate_pct": 100.0,
        }

        return AgentConsensusPlan(
            plan=plan,
            department_proposals=all_proposals,
            agreements=agreements,
            conflict_resolutions=conflict_resolutions,
            early_warnings=early_warnings,
            orchestration_summary=summary,
        )
